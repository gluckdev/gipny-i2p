"""Bounded WebSocket <-> TCP byte forwarder for the browser NTCP2 spike.

The allowlist is generated by prepare-netdb after signature verification. This
process has no I2P private keys and never terminates NTCP2 encryption.
"""
import argparse
import asyncio
import base64
from dataclasses import dataclass
import hmac
import ipaddress
import logging
from pathlib import Path
import re
import socket
import ssl
import time
from urllib.parse import parse_qs, urlsplit

from websockets.asyncio.server import serve

MAX_FRAME = 65536
MAX_BYTES = 8 * 1024 * 1024
PROTOCOL_PREFIX = "gipny.ntcp2.v1."


def one_header(headers, name):
    values = headers.get_all(name)
    return values[0] if len(values) == 1 else None


def target_address(value):
    host, port = value.rsplit(":", 1)
    address = ipaddress.IPv4Address(host)
    port = int(port)
    if not 1 <= port <= 65535 or value != f"{address}:{port}":
        raise ValueError("noncanonical target")
    return str(address), port


@dataclass
class Lease:
    writer: object = None
    received: int = 0
    sent: int = 0


class Forwarder:
    def __init__(self, capability, hosts, origins, targets, *, max_connections=8):
        if not re.fullmatch(r"[A-Za-z0-9_-]{43}", capability):
            raise ValueError("invalid capability format")
        if not hosts or not origins or not targets:
            raise ValueError("Host, Origin and target allowlists must be explicit")
        self.protocol = PROTOCOL_PREFIX + capability
        self.hosts = frozenset(hosts)
        self.origins = frozenset(origins)
        self.targets = dict(targets)  # canonical address -> Unix expiry
        self.max_connections = max_connections
        self.leases = {}
        self.watchers = set()
        self.tokens = 32.0
        self.refilled = time.monotonic()

    def select_subprotocol(self, connection, protocols):
        if len(protocols) != 1 or not hmac.compare_digest(protocols[0], self.protocol):
            return None
        return self.protocol

    async def cleanup(self, connection):
        lease = self.leases.pop(connection, None)
        if lease is not None and lease.writer is not None:
            lease.writer.close()
            try:
                await asyncio.wait_for(lease.writer.wait_closed(), 2)
            except (OSError, TimeoutError):
                pass

    async def watch_closed(self, connection):
        try:
            await connection.wait_closed()
        finally:
            await self.cleanup(connection)

    async def process_request(self, connection, request):
        # Validate before opening TCP, including duplicate headers and query
        # keys. Targets are IP literals: no DNS lookup/rebinding or proxy URL.
        deny = lambda status=403: connection.respond(status, "forwarder request rejected\n")
        try:
            if one_header(request.headers, "Host") not in self.hosts:
                return deny()
            if one_header(request.headers, "Origin") not in self.origins:
                return deny()
            key = one_header(request.headers, "Sec-WebSocket-Key")
            if key is None or len(base64.b64decode(key, validate=True)) != 16:
                return deny()
            if one_header(request.headers, "Sec-WebSocket-Version") != "13":
                return deny()
            protocol = one_header(request.headers, "Sec-WebSocket-Protocol")
            if protocol is None or not hmac.compare_digest(protocol, self.protocol):
                return deny()
            parsed = urlsplit(request.path)
            if parsed.path != "/stream" or parsed.scheme or parsed.netloc or parsed.fragment:
                return deny()
            query = parse_qs(parsed.query, strict_parsing=True, max_num_fields=2)
            if set(query) != {"target"} or len(query["target"]) != 1:
                return deny()
            target = query["target"][0]
            host, port = target_address(target)
            if self.targets.get(target, 0) <= time.time():
                return deny()
        except (ValueError, KeyError, TypeError):
            return deny()
        now = time.monotonic()
        self.tokens = min(32.0, self.tokens + now - self.refilled)
        self.refilled = now
        if self.tokens < 1 or len(self.leases) >= self.max_connections:
            return deny(429)
        self.tokens -= 1
        lease = Lease()
        self.leases[connection] = lease
        watcher = asyncio.create_task(self.watch_closed(connection))
        self.watchers.add(watcher)
        watcher.add_done_callback(self.watchers.discard)
        try:
            reader, writer = await asyncio.wait_for(
                asyncio.open_connection(host, port, family=socket.AF_INET, limit=MAX_FRAME), 5
            )
            lease.writer = writer
            # A canceled/failed upgrade may already have released admission.
            if connection not in self.leases:
                writer.close()
                return deny(502)
            connection.ntcp_reader = reader
        except (OSError, TimeoutError):
            await self.cleanup(connection)
            return deny(502)
        # Successful WebSocket upgrade means TCP is already connected.
        return None

    async def handler(self, connection):
        lease = self.leases.get(connection)
        if lease is None:
            return

        async def from_browser():
            async for message in connection:
                if not isinstance(message, bytes):
                    await connection.close(1003, "binary messages required")
                    return
                lease.received += len(message)
                if lease.received + lease.sent > MAX_BYTES:
                    await connection.close(1009, "session byte limit")
                    return
                lease.writer.write(message)
                await asyncio.wait_for(lease.writer.drain(), 15)

        async def to_browser():
            while True:
                chunk = await asyncio.wait_for(connection.ntcp_reader.read(16384), 30)
                if not chunk:
                    return
                lease.sent += len(chunk)
                if lease.received + lease.sent > MAX_BYTES:
                    await connection.close(1009, "session byte limit")
                    return
                await asyncio.wait_for(connection.send(chunk), 15)

        tasks = [asyncio.create_task(from_browser()), asyncio.create_task(to_browser())]
        try:
            done, _ = await asyncio.wait(tasks, timeout=60, return_when=asyncio.FIRST_COMPLETED)
            for task in done:
                task.result()
        except Exception:
            # No headers, capability, payloads or private state in logs/errors.
            await connection.close(1011, "forwarder transport failure")
        finally:
            for task in tasks:
                task.cancel()
            await asyncio.gather(*tasks, return_exceptions=True)
            await self.cleanup(connection)

    async def listen(self, host, port, **kwargs):
        return await serve(self.handler, host, port,
            process_request=self.process_request, select_subprotocol=self.select_subprotocol,
            compression=None, max_size=MAX_FRAME, max_queue=8, write_limit=MAX_FRAME,
            open_timeout=8, close_timeout=2, **kwargs)


def load_targets(path, allow_fixture_loopback=False):
    targets = {}
    now = time.time()
    for line in Path(path).read_text().splitlines():
        if not line or line.startswith("#"):
            continue
        target, _router_info, _peer, source, published = line.split("\t")
        host, _ = target_address(target)
        address = ipaddress.ip_address(host)
        if not address.is_global and not (allow_fixture_loopback and source == "fixture" and host == "127.0.0.1"):
            continue
        expiry = min(float(published) + 36 * 3600, now + 600)
        if expiry > now:
            targets[target] = expiry
    return targets


async def main(args):
    host, port = args.listen.rsplit(":", 1)
    address = ipaddress.ip_address(host)
    if bool(args.tls_cert) != bool(args.tls_key):
        raise ValueError("both TLS certificate and key are required")
    if not address.is_loopback and not args.tls_cert:
        raise ValueError("non-loopback listeners require TLS")
    tls = None
    if args.tls_cert:
        tls = ssl.SSLContext(ssl.PROTOCOL_TLS_SERVER)
        tls.minimum_version = ssl.TLSVersion.TLSv1_2
        tls.load_cert_chain(args.tls_cert, args.tls_key)
    capability = Path(args.capability_file).read_text().strip()
    forwarder = Forwarder(capability, args.host, args.origin,
        load_targets(args.candidates, args.allow_fixture_loopback))
    # Library debug handshake logs contain request headers, so never enable
    # them for a capability-bearing endpoint.
    logging.getLogger("websockets").setLevel(logging.CRITICAL)
    async with await forwarder.listen(host, int(port), ssl=tls):
        print(f"READY targets={len(forwarder.targets)}", flush=True)
        await asyncio.Future()


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--listen", default="127.0.0.1:18767")
    parser.add_argument("--host", action="append", required=True)
    parser.add_argument("--origin", action="append", required=True)
    parser.add_argument("--capability-file", required=True)
    parser.add_argument("--candidates", required=True)
    parser.add_argument("--allow-fixture-loopback", action="store_true")
    parser.add_argument("--tls-cert")
    parser.add_argument("--tls-key")
    asyncio.run(main(parser.parse_args()))
